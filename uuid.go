package main

import (
	"crypto/rand"
	"encoding/hex"
)

// newID returns a UUID v4 as a 32-char hex string (no dashes).
func newID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(err)
	}
	b[6] = (b[6] & 0x0f) | 0x40 // version 4
	b[8] = (b[8] & 0x3f) | 0x80 // variant 10
	return hex.EncodeToString(b[:])
}
